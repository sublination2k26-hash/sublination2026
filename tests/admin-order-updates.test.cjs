const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');

test('admin edits preserve negotiated prices and customization; ready action saves without completing tasks',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
    grant usage on schema auth to authenticated;`);
  const migration=name=>db.exec(fs.readFileSync('supabase/migrations/'+name,'utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610170001_initial_schema.sql','utf8').replace('create extension if not exists pgcrypto;','').split('-- Create a private storage bucket')[0]);
  for(const name of ['202610190002_dashboard_persistence.sql','202610190003_catalog_orders.sql','20261022012741_customer_facebook_contact.sql','20261022084023_service_production_routes.sql','20261029082024_dated_customer_downpayments.sql','20261102123339_multi_item_orders.sql','20261104100040_edit_player_rosters.sql','20261105094552_admin_ready_for_release.sql','20261106025346_order_permissions_and_deletion_backups.sql'])await migration(name);
  await migration(fs.readdirSync('supabase/migrations').find(name=>name.endsWith('_admin_order_edit_preserve_details.sql')));
  const uid='00000000-0000-0000-0000-000000000001';
  await db.query('insert into auth.users values($1)',[uid]);
  await db.query("insert into profiles(id,full_name,role) values($1,'Admin','admin')",[uid]);
  await db.query("select set_config('test.uid',$1,false)",[uid]);
  await db.exec('grant select,insert,update,delete on all tables in schema public to authenticated;grant usage,select on all sequences in schema public to authenticated;');
  const product=(await db.query("insert into products(name,category,base_price) values('Jersey','Shirts',500) returning id")).rows[0].id;
  const customer=(await db.query("insert into customers(full_name) values('Customer') returning id")).rows[0].id;
  const order=(await db.query('insert into orders(customer_id,total,subtotal) values($1,700,700) returning id',[customer])).rows[0].id;
  const customization={names:'Player',roster:[{name:'Player',number:'7',size:'M'}],intake_index:0,garment:'Jersey',production_service:'full_garment',payment_due_date:'2026-12-01'};
  const item=(await db.query("insert into order_items(order_id,product_id,product_name,quantity,unit_price,customization) values($1,$2,'Jersey',2,350,$3) returning id",[order,product,customization])).rows[0].id;
  await db.query("insert into payments(order_id,amount) values($1,700)",[order]);
  await db.query("insert into production_tasks(order_id,order_item_id,stage) values($1,$2,'layout')",[order,item]);
  await db.exec('set role authenticated');
  const edit=(names='Player',quantity=2)=>db.query("select update_catalog_order($1,'Edited customer','123',$2,$3,'2026-12-02',$4,'Edited notes')",[order,product,quantity,names]);
  await edit();
  assert.deepEqual((await db.query('select customization from order_items where id=$1',[item])).rows[0].customization,customization);
  assert.equal(Number((await db.query('select total from orders where id=$1',[order])).rows[0].total),700);
  assert.equal((await db.query('select full_name from customers where id=$1',[customer])).rows[0].full_name,'Edited customer');
  await db.query('select admin_mark_order_ready($1,$2)',[order,'Completed before encoding']);
  assert.equal((await db.query('select status from orders where id=$1',[order])).rows[0].status,'ready_for_release');
  assert.equal((await db.query('select status from production_tasks where order_id=$1',[order])).rows[0].status,'pending');
  await assert.rejects(edit('Changed',1),/lower than payments/);
  assert.deepEqual((await db.query('select customization from order_items where id=$1',[item])).rows[0].customization,customization);
  await db.exec('reset role');
  await db.query('update products set active=false where id=$1',[product]);
  await db.exec('set role authenticated');await edit();
  await db.exec('reset role');
  await db.query("insert into order_items(order_id,product_name,quantity,unit_price) values($1,'Extra',1,100)",[order]);
  await db.exec('set role authenticated');await edit('Updated names');
  assert.deepEqual((await db.query('select customization from order_items where id=$1',[item])).rows[0].customization,{...customization,names:'Updated names'});
  assert.equal((await db.query('select quantity from order_items where id=$1',[item])).rows[0].quantity,2);
  await db.exec('reset role');await db.query("update profiles set role='front_desk' where id=$1",[uid]);
  await db.exec('set role authenticated');
  await assert.rejects(edit(),/Only admins/);
  await assert.rejects(db.query('select admin_mark_order_ready($1,$2)',[order,'Bypass']),/Only admins/);
});
