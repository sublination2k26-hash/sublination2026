const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
test('cleanup is atomic and admin-only; sewer sees only own rate', async t => {
 const db = new PGlite(); t.after(()=>db.close());
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 grant usage on schema auth to authenticated;
 create type app_role as enum ('admin','front_desk','cutting_sewing');
 create table profiles(id uuid primary key,role app_role,active boolean);
 create function current_app_role() returns app_role language sql stable security definer as $$select role from public.profiles where id=auth.uid() and active$$;
 insert into profiles values ('00000000-0000-0000-0000-000000000001','admin',true),('00000000-0000-0000-0000-000000000002','cutting_sewing',true);
 create table employee_compensation(employee_id uuid,piece_rate numeric,salary_basis text);
 insert into employee_compensation values ('00000000-0000-0000-0000-000000000001',99,'piece'),('00000000-0000-0000-0000-000000000002',12,'piece');`);
 for (const file of ['20261027064919_document_routing.sql','20261029192517_document_routing_loans.sql','20261101035952_personal_loan_interest_modes.sql','20261110082318_routing_cleanup_loan_controls.sql']) await db.exec(fs.readFileSync('supabase/migrations/'+file,'utf8'));
 const act = async n => {await db.exec('reset role'); await db.query("select set_config('test.uid',$1,false)",[`00000000-0000-0000-0000-00000000000${n}`]);await db.exec('set role authenticated');};
 await act(1);
 const doc=(await db.query("insert into routing_documents(pr_number,title,request_date) values ('TEST','Test','2026-01-01') returning id")).rows[0].id;
 await db.query("insert into document_routing_entries(document_id,stage,received_date) values ($1,'P.R.','2026-01-01')",[doc]);
 const loan=(await db.query("insert into personal_loans(borrower_name,principal,start_date,first_due_date,due_day,monthly_interest) values ('Ana',100,'2026-01-01','2026-02-01',1,0) returning id")).rows[0].id;
 await db.query("insert into personal_loan_payments(loan_id,paid_on,principal_amount) values ($1,'2026-02-01',100)",[loan]);
 await db.query('update personal_loans set archived_at=now() where id=$1',[loan]);
 await act(2);
 assert.equal((await db.query('select * from get_own_sewing_rate()')).rows[0].piece_rate,'12');
 await assert.rejects(db.query('select delete_routing_document($1)',[doc]),/Admin access/);
 await assert.rejects(db.query('select delete_personal_loan($1)',[loan]),/Admin access/);
 await act(1);
 assert.equal((await db.query('select * from get_own_sewing_rate()')).rows.length,0);
 await db.query('select delete_routing_document($1)',[doc]);
 await db.query('select delete_personal_loan($1)',[loan]);
 for (const table of ['routing_documents','document_routing_entries','personal_loans','personal_loan_payments']) assert.equal((await db.query(`select count(*)::int as n from ${table}`)).rows[0].n,0);
});
