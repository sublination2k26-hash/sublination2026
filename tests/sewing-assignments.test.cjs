const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { randomUUID } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');

test('Front Desk assignments, gated handoffs, separate sewer output and payroll attribution', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
    grant usage on schema auth to authenticated, anon;`);
  const initial = fs.readFileSync('supabase/migrations/202610170001_initial_schema.sql', 'utf8')
    .replace('create extension if not exists pgcrypto;', '').split('-- Create a private storage bucket')[0];
  await db.exec(initial);
  for (const file of ['202610190002_dashboard_persistence.sql', '202610190003_catalog_orders.sql', '20261022012741_customer_facebook_contact.sql', '20261022084023_service_production_routes.sql', '202610200007_employee_work_payroll.sql', '202610200008_automatic_task_payroll_tracking.sql', '20261026060520_sewing_only_work_tracking.sql']) {
    await db.exec(fs.readFileSync(`supabase/migrations/${file}`, 'utf8'));
  }
  await db.exec(`grant select,insert,update,delete on all tables in schema public to authenticated;
    grant usage,select on all sequences in schema public to authenticated;`);
  for (const [n, role] of [[1,'admin'],[2,'front_desk'],[3,'cutting_sewing'],[4,'cutting_sewing'],[5,'artist'],[6,'qc']]) {
    await db.query('insert into auth.users values ($1)', [id(n)]);
    await db.query('insert into profiles(id,full_name,role) values ($1,$2,$3)', [id(n), `Employee ${n}`, role]);
  }
  await db.query("insert into employee_compensation(employee_id,salary_basis,piece_rate) values ($1,'piece',30),($2,'combined',40)", [id(3),id(4)]);
  await db.exec(fs.readFileSync('supabase/migrations/20261029065538_sewer_assignments.sql', 'utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/20261029074932_sewer_self_claim.sql', 'utf8'));
  const asUser = async n => {
    await db.exec('reset role');
    await db.query("select set_config('test.uid',$1,false)", [n ? id(n) : '']);
    await db.exec('set role authenticated');
  };
  const action = async (kind, task, assignment, employee, qty, request=randomUUID(), notes='') =>
    (await db.query('select record_sewing_action($1,$2,$3,$4,$5,$6,$7) as id', [kind,task,assignment,employee,qty,notes,request])).rows[0].id;
  const product=(await db.query("insert into products(name,category,production_type,production_service,base_price) values ('Jersey','Team jerseys','full_garment','full_garment',350) returning id")).rows[0].id;
  await asUser(2);
  const order = (await db.query("select create_catalog_order_with_contact('Test team','',$1,13,current_date+7,0,'S 3, M 5, L 5','Test','') as id",[product])).rows[0].id;
  const task = (await db.query("select id,order_item_id from production_tasks where order_id=$1 and stage='sewing'", [order])).rows[0];
  const a = await action('assign', task.id, null, id(3), 8);
  const b = await action('assign', task.id, null, id(4), 5);
  assert.equal(await action('assign', task.id, null, id(3), 8, a), a, 'assignment retry is idempotent');
  await assert.rejects(action('assign',task.id,null,id(3),1), /exceed the order item/);
  await assert.rejects(action('assign',task.id,null,id(5),1), /active sewer/);
  await assert.rejects(action('handoff',task.id,a,null,3), /Waiting for materials/);
  await assert.rejects(db.query('update order_items set quantity=12 where id=$1',[task.order_item_id]), /cannot be changed/);
  await assert.rejects(db.exec('delete from sewing_assignments'), /permission denied/);
  await assert.rejects(db.query("insert into sewing_assignments values ($1,$2,$3,1,$4,'',now())",[randomUUID(),task.id,id(3),id(2)]), /permission denied/);
  await asUser(3);
  assert.equal((await db.query('select * from sewing_assignments')).rows.length,1, 'sewer sees only own assignment before materials ready');
  await assert.rejects(action('completion',task.id,b,null,1), /own sewing output/);
  await assert.rejects(action('assign',task.id,null,id(3),1), /Only admin or front desk/);
  await assert.rejects(action('handoff',task.id,a,null,1), /Only admin or front desk/);
  await assert.rejects(db.query("update production_tasks set status='completed',completed_by=auth.uid() where id=$1",[task.id]), /earlier production/);
  await asUser(1);
  await db.query("update production_tasks set status='completed',completed_at=now() where order_id=$1 and stage<'sewing'", [order]);
  await assert.rejects(db.query("update production_tasks set status='completed' where order_id=$1 and stage='qc'",[order]), /all assigned sewing/);
  await asUser(3);
  await assert.rejects(action('completion',task.id,a,null,1), /exceeds pieces handed/);
  await asUser(2);
  const hand = await action('handoff',task.id,a,null,3);
  assert.equal(await action('handoff',task.id,a,null,3,hand),hand);
  await assert.rejects(action('handoff',task.id,a,null,6), /exceeds assigned/);
  await action('handoff',task.id,b,null,5);
  await asUser(3);
  const output = await action('completion',task.id,a,null,2);
  assert.equal(await action('completion',task.id,a,null,2,output),output, 'output retry creates no duplicate work record');
  await assert.rejects(action('completion',task.id,a,null,3,output), /different details/);
  await assert.rejects(action('completion',task.id,a,null,2), /exceeds pieces handed/);
  await action('completion',task.id,a,null,1);
  assert.equal((await db.query('select * from sewing_events')).rows.length,3);
  assert.equal((await db.query('select status from production_tasks where id=$1',[task.id])).rows[0].status,'in_progress');
  await assert.rejects(db.query("update production_tasks set status='completed',completed_by=auth.uid() where id=$1",[task.id]), /every assigned sewer output/);
  await asUser(4);
  await action('completion',task.id,b,null,5);
  await asUser(2);
  await action('handoff',task.id,a,null,5);
  await asUser(3);
  await action('completion',task.id,a,null,5);
  assert.equal((await db.query('select status from production_tasks where id=$1',[task.id])).rows[0].status,'completed');
  await asUser(1);
  const records = (await db.query('select employee_id,sum(quantity)::integer as qty,sum(quantity*unit_rate) as pay from employee_work_records group by employee_id order by employee_id')).rows;
  assert.deepEqual(records.map(row=>[row.employee_id,row.qty,Number(row.pay)]),[[id(3),8,240],[id(4),5,200]]);
  assert.equal((await db.query('select count(*)::integer as n from employee_work_records')).rows[0].n,4,'final task completion does not add full-order payroll record');
  assert.ok((await db.query("select * from employee_work_records where status<>'pending_review'")).rows.length===0);
  await asUser(3);
  await assert.rejects(action('rework',task.id,a,null,1), /Rework needs a reason/);
  await action('rework',task.id,a,null,2,randomUUID(),'Fix seam');
  await asUser(1);
  const rework=(await db.query("select * from employee_work_records where is_rework")).rows[0];
  assert.equal(rework.pay_eligible,false);
  assert.equal(Number(rework.quantity),2);
  assert.equal((await db.query("select sum(quantity)::integer as n from sewing_events where kind='completion'")).rows[0].n,13);
  await asUser(5);
  assert.equal((await db.query('select * from sewing_assignments')).rows.length,0);
  await assert.rejects(action('completion',task.id,a,null,1), /Only the assigned sewer/);
  await asUser(null);
  await assert.rejects(action('assign',task.id,null,id(3),1), /active staff/);
  await asUser(1);
  const sample=(await db.query('select create_sewing_example_order() as id')).rows[0].id;
  assert.equal((await db.query('select create_sewing_example_order() as id')).rows[0].id,sample);
  const sampleItem=(await db.query('select * from order_items where order_id=$1',[sample])).rows[0];
  assert.equal(sampleItem.quantity,24);
  assert.equal((await db.query('select * from production_tasks where order_id=$1',[sample])).rows.length,6);
  const sampleTask=(await db.query("select id from production_tasks where order_id=$1 and stage='sewing'",[sample])).rows[0].id;
  const sampleAssignment=await action('assign',sampleTask,null,id(3),24);
  await db.query("update production_tasks set status='completed' where order_id=$1 and stage<'sewing'",[sample]);
  await action('handoff',sampleTask,sampleAssignment,null,24);
  await asUser(3);
  await action('completion',sampleTask,sampleAssignment,null,24);
  await asUser(1);
  assert.equal((await db.query('select pay_eligible from employee_work_records where task_id=$1',[sampleTask])).rows[0].pay_eligible,false);
  // A different quantity, initially unassigned: no generic completion bypass.
  const laterOrder=(await db.query("select create_dashboard_order('Second team','','Jersey','full_garment',7,current_date+3,300,0,'','') as id")).rows[0].id;
  const laterTask=(await db.query("select id from production_tasks where order_id=$1 and stage='sewing'",[laterOrder])).rows[0].id;
  await db.query("update production_tasks set status='completed' where order_id=$1 and stage<'sewing'",[laterOrder]);
  await assert.rejects(db.query("update production_tasks set status='completed',completed_by=$2 where id=$1",[laterTask,id(3)]), /every assigned sewer output/);
  await assert.rejects(db.query("update production_tasks set status='in_progress' where id=$1",[laterTask]), /assign and hand over/);
  await assert.rejects(db.query('update production_tasks set sewing_tracking=false where id=$1',[laterTask]), /cannot be disabled/);
  const early=await action('assign',laterTask,null,id(3),3);
  await action('handoff',laterTask,early,null,3);
  await asUser(3);
  await action('completion',laterTask,early,null,3);
  await asUser(2);
  const later=await action('assign',laterTask,null,id(4),4);
  await action('handoff',laterTask,later,null,4);
  await asUser(4);
  await action('completion',laterTask,later,null,4);
  assert.equal((await db.query('select status from production_tasks where id=$1',[laterTask])).rows[0].status,'completed');
  await asUser(1);
  await db.query("update orders set status='cancelled' where id=$1",[laterOrder]);
  await asUser(4);
  await assert.rejects(action('rework',laterTask,later,null,1,randomUUID(),'Cancelled'), /no longer accepting/);
  await asUser(1);
  // A newly encoded order is visible in the shared queue BEFORE any assignment.
  const sharedOrder=(await db.query("select create_catalog_order_with_contact('Shared team','',$1,9,current_date+3,0,'','Shared queue','') as id",[product])).rows[0].id;
  const sharedTask=(await db.query("select id from production_tasks where order_id=$1 and stage='sewing'",[sharedOrder])).rows[0].id;
  const claim=(quantity,request=randomUUID(),notes='')=>db.query('select claim_sewing_pieces($1,$2,$3,$4) as id',[sharedTask,quantity,notes,request]);
  await asUser(3);
  let shared=(await db.query('select * from get_sewing_queue() where task_id=$1',[sharedTask])).rows[0];
  assert.equal(Number(shared.available_quantity),9);
  const ownClaim=(await claim(4)).rows[0].id;
  assert.equal((await claim(4,ownClaim)).rows[0].id,ownClaim,'claim retries reuse the assignment');
  await assert.rejects(claim(3,ownClaim),/different details/);
  await assert.rejects(claim(0),/positive whole quantity/);
  const own=(await db.query('select * from sewing_assignments where id=$1',[ownClaim])).rows[0];
  assert.equal(own.employee_id,id(3)); assert.equal(own.assigned_by,id(3),'sewer is the assignment recorder');
  await assert.rejects(action('completion',sharedTask,ownClaim,null,1),/Waiting for materials/);
  await asUser(4);
  shared=(await db.query('select * from get_sewing_queue() where task_id=$1',[sharedTask])).rows[0];
  assert.equal(Number(shared.available_quantity),5,'availability includes other sewers despite private assignment rows');
  assert.equal((await db.query('select * from sewing_assignments where task_id=$1',[sharedTask])).rows.length,0);
  await assert.rejects(claim(6),/Not enough unclaimed pieces/);
  const secondClaim=(await claim(5)).rows[0].id;
  assert.equal(Number((await db.query('select * from get_sewing_queue() where task_id=$1',[sharedTask])).rows[0].available_quantity),0);
  await asUser(3);
  await assert.rejects(claim(1),/Not enough unclaimed pieces/);
  await assert.rejects(action('completion',sharedTask,secondClaim,null,1),/own sewing output/);
  await asUser(1);
  assert.equal((await db.query('select count(*)::integer as n from employee_work_records where task_id=$1',[sharedTask])).rows[0].n,0,'claiming is not finished output');
  await db.query("update production_tasks set status='completed' where order_id=$1 and stage<'sewing'",[sharedOrder]);
  await action('handoff',sharedTask,ownClaim,null,4);
  await action('handoff',sharedTask,secondClaim,null,5);
  await asUser(3); await action('completion',sharedTask,ownClaim,null,4);
  await asUser(4); await action('completion',sharedTask,secondClaim,null,5);
  assert.equal((await db.query('select * from get_sewing_queue() where task_id=$1',[sharedTask])).rows.length,0,'completed sewing leaves shared queue');
  await asUser(5);
  await assert.rejects(db.query('select * from get_sewing_queue()'),/active sewing/);
  await assert.rejects(claim(1),/Only an active sewer/);
  await asUser(2); await assert.rejects(claim(1),/Only an active sewer/);
  await asUser(null); await assert.rejects(db.query('select * from get_sewing_queue()'),/active sewing/);
  await asUser(1);
  await db.query('update profiles set active=false where id=$1',[id(3)]);
  await asUser(3);
  assert.equal((await db.query('select * from sewing_assignments')).rows.length,0);
  await assert.rejects(action('rework',task.id,a,null,1,randomUUID(),'Inactive'), /active staff/);
  await assert.rejects(claim(1),/Only an active sewer/);
});
