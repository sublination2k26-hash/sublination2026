const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
test('employee advances: individual balances, payroll reservations, locks and access control',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 grant usage on schema auth to authenticated,anon;
 create type app_role as enum ('admin','artist');
 create table profiles(id uuid primary key,role app_role,active boolean);
 create function current_app_role() returns app_role language sql stable security definer as $$select role from public.profiles where id=auth.uid() and active$$;
 insert into profiles values ('00000000-0000-0000-0000-000000000001','admin',true),('00000000-0000-0000-0000-000000000002','artist',true),('00000000-0000-0000-0000-000000000003','artist',true);
 create table payroll_runs(id uuid primary key default gen_random_uuid(),status text,period_start date,period_end date);
 create table payroll_lines(id uuid primary key default gen_random_uuid(),payroll_run_id uuid references payroll_runs,employee_id uuid references profiles,base_pay numeric default 1000,production_pay numeric default 0,adjustments numeric default 0,cash_advance numeric default 0,total_pay numeric default 1000);
 create function guard_payroll_line_adjustments() returns trigger language plpgsql as $$begin return new;end$$;
 create trigger payroll_lines_draft_adjustments before update on payroll_lines for each row execute function guard_payroll_line_adjustments();
 insert into payroll_runs(status,period_start,period_end) values ('paid','2026-01-01','2026-01-15');
 insert into payroll_lines(payroll_run_id,employee_id,cash_advance,total_pay) select id,'00000000-0000-0000-0000-000000000002',100,900 from payroll_runs;
 `);
 await db.exec(fs.readFileSync('supabase/migrations/20261027124647_employee_cash_advance_ledger.sql','utf8'));
 await db.exec(fs.readFileSync('supabase/migrations/20261027131046_payroll_overtime.sql','utf8'));
 assert.equal(Number((await db.query('select legacy_cash_advance from payroll_lines')).rows[0].legacy_cash_advance),100);
 const asUser=async id=>{await db.exec('reset role');await db.query("select set_config('test.uid',$1,false)",[`00000000-0000-0000-0000-00000000000${id}`]);await db.exec('set role authenticated');};
 await asUser(1);
 const issue=async(amount,ref='CA-001',employee='00000000-0000-0000-0000-000000000002')=>(await db.query("select issue_employee_cash_advance($1,$2,'2026-01-16',$3,'Medical expenses') as id",[employee,amount,ref])).rows[0].id;
 const advance=await issue(3000);
 await assert.rejects(issue(200,'CA-001'),/unique/);
 await assert.rejects(issue(-1,'BAD'),/check constraint/);
 const second=await issue(1000,'CA-002');
 await db.exec('reset role');
 const run=(await db.query("insert into payroll_runs(status,period_start,period_end) values ('draft','2026-01-16','2026-01-31') returning id")).rows[0].id;
 const line=(await db.query("insert into payroll_lines(payroll_run_id,employee_id) values ($1,'00000000-0000-0000-0000-000000000002') returning id",[run])).rows[0].id;
 const other=(await db.query("insert into payroll_lines(payroll_run_id,employee_id) values ($1,'00000000-0000-0000-0000-000000000003') returning id",[run])).rows[0].id;
 const nextRun=(await db.query("insert into payroll_runs(status,period_start,period_end) values ('draft','2026-02-01','2026-02-15') returning id")).rows[0].id;
 const nextLine=(await db.query("insert into payroll_lines(payroll_run_id,employee_id) values ($1,'00000000-0000-0000-0000-000000000002') returning id",[nextRun])).rows[0].id;
 await asUser(1);
 const recover=(l,a,n)=>db.query('select set_payroll_advance_recovery($1,$2,$3)',[l,a,n]);
 await recover(line,advance,500);
 await recover(line,second,100);
 await db.exec('reset role');
 let row=(await db.query('select * from payroll_lines where id=$1',[line])).rows[0];
 assert.equal(Number(row.cash_advance),600);assert.equal(Number(row.total_pay),400);
 await db.query('update payroll_lines set overtime_hours=2.5,overtime_rate=60 where id=$1',[line]);
 row=(await db.query('select * from payroll_lines where id=$1',[line])).rows[0];
 assert.equal(Number(row.overtime_pay),150);assert.equal(Number(row.total_pay),550);
 await assert.rejects(db.query('update payroll_lines set overtime_hours=-1 where id=$1',[line]),/check constraint/);
 await assert.rejects(db.query("update payroll_lines set overtime_rate='NaN' where id=$1",[line]),/check constraint/);
 await asUser(1);
 await assert.rejects(recover(other,advance,50),/belong/);
 await assert.rejects(recover(nextLine,advance,2600),/exceeds/);
 await recover(nextLine,advance,2500);
 await recover(nextLine,advance,0);
 await recover(line,advance,500); // Setting the same amount is idempotent.
 await db.exec('reset role');
 assert.equal(Number((await db.query('select total_pay from payroll_lines where id=$1',[line])).rows[0].total_pay),550);
 await asUser(1);
 await assert.rejects(db.exec('delete from employee_cash_advances'),/permission denied/);
 await assert.rejects(db.exec('delete from payroll_advance_recoveries'),/permission denied/);
 await db.exec('reset role');
 await assert.rejects(db.query('update payroll_lines set cash_advance=1 where id=$1',[line]),/individual advances/);
 await db.query("update payroll_runs set status='paid' where id=$1",[run]);
 await assert.rejects(db.query('update payroll_lines set overtime_hours=5 where id=$1',[line]),/Only draft/);
 await asUser(1);await assert.rejects(recover(line,advance,100),/draft/);
 const history=(await db.query('select * from payroll_advance_recoveries where advance_id=$1',[advance])).rows;
 assert.equal(history.length,1);assert.equal(3000-Number(history[0].amount),2500);
 await asUser(2);
 assert.equal((await db.query('select * from employee_cash_advances')).rows.length,0);
 assert.equal((await db.query('select * from payroll_advance_recoveries')).rows.length,0);
 await assert.rejects(issue(100,'BLOCKED'),/active admin/);
 await assert.rejects(recover(nextLine,advance,100),/active admin/);
 await db.exec('reset role;set role anon');
 await assert.rejects(db.exec('select * from employee_cash_advances'),/permission denied/);
});
