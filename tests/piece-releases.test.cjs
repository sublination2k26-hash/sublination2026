const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');

test('partial pickups preserve remaining quantities, permissions, payment gates and final release', async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(`
    create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
    grant usage on schema auth to authenticated;
    create table profiles(id uuid primary key, role text, active boolean default true);
    insert into profiles values ('00000000-0000-0000-0000-000000000001','admin',true),('00000000-0000-0000-0000-000000000002','front_desk',true),('00000000-0000-0000-0000-000000000003','artist',true);
    create function current_app_role() returns text language sql stable security definer as $$select role from public.profiles where id=auth.uid() and active$$;
    create table orders(id uuid primary key default gen_random_uuid(), status text default 'ready_for_release', total numeric default 100, release_date timestamptz, updated_at timestamptz, release_exception_reason text, release_exception_by uuid);
    create table order_items(id uuid primary key default gen_random_uuid(),order_id uuid references orders,quantity integer);
    create table payments(order_id uuid,amount numeric);
    create table qc_inspections(order_id uuid,status text,quantity_verified boolean default true,sizes_verified boolean default true,personalization_verified boolean default true,print_quality_verified boolean default true,condition_verified boolean default true);
    grant select,insert,update,delete on all tables in schema public to authenticated;
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261029025401_order_piece_releases.sql', 'utf8'));
  const order = (await db.query('insert into orders default values returning id')).rows[0].id;
  await db.query('insert into order_items(order_id,quantity) values ($1,10)', [order]);
  const asUser = async n => { await db.exec('reset role'); await db.query("select set_config('test.uid',$1,false)", [`00000000-0000-0000-0000-00000000000${n}`]); await db.exec('set role authenticated'); };
  const pickup = (quantity, reason = '') => db.query("insert into order_releases(order_id,quantity,received_by,released_by,exception_reason) values ($1,$2,'Customer',auth.uid(),$3)", [order, quantity, reason]);
  await asUser(2);
  await assert.rejects(pickup(3), /QC and full payment/);
  await db.query('insert into payments values ($1,100)', [order]);
  await db.query("insert into qc_inspections(order_id,status) values ($1,'approved')", [order]);
  await pickup(3);
  assert.equal((await db.query('select status from orders where id=$1', [order])).rows[0].status, 'ready_for_release');
  await assert.rejects(pickup(8), /remaining pieces/);
  await assert.rejects(pickup(0), /invalid/);
  await assert.rejects(db.query('update order_items set quantity=2 where order_id=$1', [order]), /cannot be changed/);
  await assert.rejects(db.query("update orders set status='released' where id=$1", [order]), /remaining pieces/);
  await assert.rejects(db.exec('delete from order_releases'), /permission denied/);
  await asUser(3);
  await assert.rejects(pickup(1), /Only admin or front desk/);
  await asUser(2);
  await pickup(7);
  assert.equal((await db.query('select status from orders where id=$1', [order])).rows[0].status, 'released');
  assert.equal(Number((await db.query('select sum(quantity) as qty from order_releases')).rows[0].qty), 10);
  await assert.rejects(pickup(1), /already released/);
  await db.exec('reset role');
  const unpaid = (await db.query('insert into orders default values returning id')).rows[0].id;
  await db.query('insert into order_items(order_id,quantity) values ($1,2)', [unpaid]);
  await asUser(2);
  await assert.rejects(db.query("insert into order_releases(order_id,quantity,received_by,released_by,exception_reason) values ($1,1,'Customer',auth.uid(),'Owner said yes')", [unpaid]), /QC and full payment/);
  await asUser(1);
  await db.query("insert into order_releases(order_id,quantity,received_by,released_by,exception_reason) values ($1,1,'Customer',auth.uid(),'Owner approved partial pickup')", [unpaid]);
  await db.exec('reset role');
  await db.exec(fs.readFileSync('supabase/migrations/20261029030118_pickup_release_dates.sql', 'utf8'));
  const backfilled = (await db.query("select count(*) as count from order_releases where release_on is null or release_on <> (released_at at time zone 'Asia/Manila')::date")).rows[0];
  assert.equal(Number(backfilled.count), 0);
  await asUser(1);
  const result = await db.query("insert into order_releases(order_id,quantity,received_by,released_by,exception_reason,release_on) values ($1,1,'Customer',auth.uid(),'Owner approved remaining pickup','2026-10-20') returning release_on::text,released_at", [unpaid]);
  assert.equal(result.rows[0].release_on, '2026-10-20');
  const completed = (await db.query("select status,(release_date at time zone 'Asia/Manila')::date::text as date from orders where id=$1", [unpaid])).rows[0];
  assert.equal(completed.status, 'released');
  assert.equal(completed.date, '2026-10-20');
  assert.notEqual(new Date(result.rows[0].released_at).toISOString().slice(0,10), '2026-10-20');
});
